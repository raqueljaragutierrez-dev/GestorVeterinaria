class Producto {
  final int id;
  final String nombre;
  final String descripcion;
  final double precio;
  final String categoria;
  final String tipo;
  final String imagen;

  Producto({
    required this.id,
    required this.nombre,
    required this.descripcion,
    required this.precio,
    required this.categoria,
    required this.tipo,
    required this.imagen,
  });
}
